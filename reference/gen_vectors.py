#!/usr/bin/env python3
"""Generate cross-implementation test vectors for the Rust crate.

The vectors are produced by `ethiopic_ref.py`, an independent Python
transcription of Reingold & Dershowitz's algorithms, and are additionally
cross-checked (see `crosscheck.py`) against:

  * CPython's `datetime.date.toordinal` — proleptic Gregorian,
  * `convertdate.coptic` — the Coptic calendar, which shares the Ethiopic
    structure with a 276-year offset,
  * the Julian-calendar paschal computus, for Fasika.

Regenerate with:

    python3 reference/gen_vectors.py

The output is committed so that the Rust test suite has no Python dependency.
"""

from __future__ import annotations

import datetime
import random
from pathlib import Path

from ethiopic_ref import (
    RD_TO_JDN,
    bahire_hasab,
    ethiopic_from_fixed,
    ethiopic_leap,
    fixed_from_ethiopic,
    fixed_from_gregorian,
    gregorian_from_fixed,
    julian_from_fixed,
    orthodox_easter_rd,
)

OUT = Path(__file__).resolve().parent.parent / "crates" / "ethiopic-calendar" / "tests" / "data"

WEEKDAYS = ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"]


def interesting_rds() -> list[int]:
    """Boundary-heavy, deterministic sample of fixed day numbers."""
    rds: set[int] = set()

    # The epochs themselves and their neighbourhoods.
    for anchor in (1, -1, 2796, 103605, 719163, 730120, 0):
        rds.update(range(anchor - 3, anchor + 4))

    # Every Ethiopian year boundary and every epagomenal day, -1000..3000 A.M.
    for year in range(-500, 2501):
        ny = fixed_from_ethiopic(year, 1, 1)
        rds.update((ny - 1, ny, ny + 1))
        pagume1 = fixed_from_ethiopic(year, 13, 1)
        last = 6 if ethiopic_leap(year) else 5
        rds.update(range(pagume1 - 1, pagume1 + last + 1))

    # Gregorian century leap rules: 1500/1600/1700/1900/2000/2100 boundaries.
    for gy in (1500, 1582, 1600, 1700, 1800, 1900, 2000, 2100, 2400):
        for md in ((2, 28), (3, 1), (12, 31), (1, 1), (9, 11), (9, 12)):
            try:
                rds.add(fixed_from_gregorian(gy, *md))
            except ValueError:
                pass

    # Deterministic pseudo-random spread over ~4400 years around the epoch.
    rng = random.Random(0xE71071)
    for _ in range(2500):
        rds.add(rng.randint(-400_000, 1_200_000))

    return sorted(rds)


def write_conversion_vectors() -> int:
    rows = []
    for rd in interesting_rds():
        gy, gm, gd = gregorian_from_fixed(rd)
        jy, jm, jd = julian_from_fixed(rd)
        ey, em, ed = ethiopic_from_fixed(rd)
        # Independent confirmation from CPython for the Gregorian side.
        if 1 <= rd <= datetime.date.max.toordinal():
            assert datetime.date.fromordinal(rd) == datetime.date(gy, gm, gd), rd
        rows.append(
            "\t".join(
                map(
                    str,
                    (
                        rd,
                        rd + RD_TO_JDN,
                        gy, gm, gd,
                        jy, jm, jd,
                        ey, em, ed,
                        WEEKDAYS[rd % 7],
                        30 * (em - 1) + ed,
                        int(ethiopic_leap(ey)),
                    ),
                )
            )
        )
    header = (
        "# rd\tjdn\tg_year\tg_month\tg_day\tj_year\tj_month\tj_day\t"
        "e_year\te_month\te_day\tweekday\te_doy\te_leap\n"
        "# generated by reference/gen_vectors.py — do not edit by hand\n"
    )
    (OUT / "conversions.tsv").write_text(header + "\n".join(rows) + "\n")
    return len(rows)


def write_computus_vectors() -> int:
    rows = []
    for year in range(1, 3001):
        h = bahire_hasab(year)
        bm_m, bm_d = h["beale_metqi"]
        nineveh = h["feasts"]["nineveh"]
        fasika = h["feasts"]["tinsae"]
        # Independent confirmation: the Julian-calendar computus.
        assert fasika == orthodox_easter_rd(year + 8), year
        rows.append(
            "\t".join(
                map(
                    str,
                    (
                        year,
                        h["amete_alem"],
                        h["medeb"],
                        h["wenber"],
                        h["abektie"],
                        h["metqi"],
                        bm_m,
                        bm_d,
                        h["mebaja_hamer"],
                        nineveh,
                        fasika,
                        h["evangelist"],
                    ),
                )
            )
        )
    header = (
        "# e_year\tamete_alem\tmedeb\twenber\tabektie\tmetqi\tbm_month\tbm_day\t"
        "mebaja_hamer\tnineveh_rd\tfasika_rd\tevangelist\n"
        "# generated by reference/gen_vectors.py — do not edit by hand\n"
    )
    (OUT / "computus.tsv").write_text(header + "\n".join(rows) + "\n")
    return len(rows)


if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    n1 = write_conversion_vectors()
    n2 = write_computus_vectors()
    print(f"wrote {n1} conversion vectors and {n2} computus vectors to {OUT}")
